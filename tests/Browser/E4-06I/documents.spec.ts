import { expect, test } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';
let server: ViteDevServer; let url: string;
test.setTimeout(60000);
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E4-06I/vite.config.ts' }); await server.listen(); url = new URL('/tests/Browser/E4-06I/fixture.html?imports', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('таблица показывает типы, статусы и доступные действия', async ({ page }) => {
 await page.goto(url);
 const saved = page.getByRole('row').filter({ hasText: 'Ранее.pdf' });
 await expect(saved).toContainText('Импортирован');
 await expect(saved.locator('svg')).toHaveCount(1);
 await expect(saved.getByRole('button', { name: 'Посмотреть', exact: true })).toBeVisible();
 await expect(saved.getByRole('link', { name: 'Скачать исходник' })).toBeVisible();
 const old = page.getByRole('row').filter({ hasText: 'Старый.txt' });
 await expect(old).toContainText('Факты предложены');
 await expect(old).toContainText('Исходник недоступен');
 await mkdir('.local/screenshots/SP-E4-06I', { recursive: true });
 await page.screenshot({ path: '.local/screenshots/SP-E4-06I/documents.png', fullPage: true });
});
