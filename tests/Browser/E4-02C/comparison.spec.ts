import { expect, test } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';
let server: ViteDevServer; let url: string;
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E4-02C/vite.config.ts', cacheDir: '.local/runtime/vite-e402c', server: { host: '127.0.0.1', port: 0, strictPort: false } }); await server.listen(); url = new URL('/tests/Browser/E4-02C/fixture.html?card', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('сравнивает опубликованный текст с редактируемым и считает символы', async ({ page }) => {
  await page.goto(url);
  await expect(page.getByText('Доставка по городу', { exact: true })).toBeVisible();
  await expect(page.locator('p').getByText('Доставка по России', { exact: true })).toBeVisible();
  const field = page.locator('textarea').first();
  await page.getByLabel('Тема', { exact: true }).selectOption('payment');
  await expect(page.getByLabel('Тема', { exact: true })).toHaveValue('payment');
  await expect(page.getByText('Правила выбранной темы появятся после сохранения.')).toBeVisible();
  await expect(page.getByText('Нельзя говорить: Не обещать срок')).toHaveCount(0);
  await expect(page.getByText('Вопрос об оплате')).toBeVisible();
  await page.getByLabel('Добавить условие').selectOption('min_order_rub');
  await expect(field).toHaveValue(/\{cond:min_order_rub\}/);
  await page.getByRole('button', { name: 'Убрать условие Минимальный заказ' }).click();
  await expect(field).not.toHaveValue(/\{cond:min_order_rub\}/);
  await field.fill('Новый текст');
  await expect(page.getByText('11 / 500 знаков')).toBeVisible();
  await expect(page.locator('p').getByText('Новый текст', { exact: true })).toBeVisible();
  await mkdir('.local/screenshots/SP-E4-02C', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/SP-E4-02C/card.png', fullPage: true });
  await page.route('**/seller/knowledge/facts/**', route => route.abort('failed'));
  await page.getByRole('button', { name: 'Сохранить факт' }).click();
  await expect(page.getByRole('alert')).toContainText('Нет связи');
  await expect(field).toHaveValue('Новый текст');
});
