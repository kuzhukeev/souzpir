import { test, expect } from '@playwright/test';
test.use({ launchOptions: process.env.ORGANIZATIONS_CHROMIUM_PATH ? { executablePath: process.env.ORGANIZATIONS_CHROMIUM_PATH } : {} });
test.skip(process.env.RUN_ORGANIZATIONS_E2E !== '1', 'Requires the dedicated organizations test server and fixture');
const base = process.env.ORGANIZATIONS_BASE_URL || 'http://127.0.0.1:8104';
test('real owner changes company, creates and archives a brand, toggles a module and transfers ownership', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + '/login');
  await page.getByLabel('Рабочая почта').fill('organizations-e104-owner@example.test');
  await page.getByLabel('Пароль', { exact: true }).fill('test-only-password-123');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page).toHaveURL(/auth\/ready/);
  await page.goto(base + '/company');
  await page.getByLabel('Название компании').fill('Компания Союз Пир');
  await page.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Изменения сохранены' })).toBeVisible();
  await page.reload(); await expect(page.getByLabel('Название компании')).toHaveValue('Компания Союз Пир');
  await page.getByRole('link', { name: 'Бренды', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить бренд' }).click();
  const create = page.getByRole('dialog', { name: 'Добавить бренд' });
  await create.getByLabel('Название бренда').fill('Новый бренд');
  await create.getByRole('button', { name: 'Создать бренд' }).click();
  const card = page.getByRole('article').filter({ hasText: 'Новый бренд' });
  await expect(card).toBeVisible();
  await card.getByRole('link', { name: 'Модули' }).click();
  await page.getByRole('switch', { name: 'Включить Видение' }).click();
  await expect(page.getByRole('switch', { name: 'Отключить Видение' })).toHaveAttribute('aria-checked', 'true');
  await page.reload(); await expect(page.getByRole('switch', { name: 'Отключить Видение' })).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('switch', { name: 'Отключить Видение' }).click();
  await page.getByRole('dialog', { name: 'Отключить модуль' }).getByRole('button', { name: 'Отключить', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Включить Видение' })).toHaveAttribute('aria-checked', 'false');
  await page.getByRole('link', { name: 'Все бренды' }).click();
  await page.getByRole('article').filter({ hasText: 'Новый бренд' }).getByRole('button', { name: 'В архив' }).click();
  const archive = page.getByRole('dialog', { name: 'Архивировать бренд' });
  await archive.getByLabel('Введите название бренда для подтверждения').fill('Новый бренд');
  await archive.getByRole('button', { name: 'Архивировать', exact: true }).click();
  await page.getByRole('button', { name: 'Архивные' }).click(); await expect(page.getByText('Новый бренд')).toBeVisible();
  await page.getByRole('link', { name: 'Компания', exact: true }).click();
  await page.getByRole('button', { name: 'Передать владение' }).click();
  const transfer = page.getByRole('dialog', { name: 'Передать владение' });
  await transfer.getByRole('combobox', { name: 'Новый владелец' }).click();
  await page.getByRole('option', { name: /organizations-e104-member@example.test/ }).click();
  await transfer.getByLabel('Введите название компании для подтверждения').fill('Компания Союз Пир');
  await transfer.getByRole('button', { name: 'Передать владение', exact: true }).click();
  await expect(page.getByText('Владение передано.')).toBeVisible();
  await expect(page.getByText('organizations-e104-member@example.test')).toBeVisible();
});
