import { test, expect } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';
let server: ViteDevServer;
let url: string;
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E4-06F/vite.config.ts', server: { host: '127.0.0.1', port: 0 } }); await server.listen(); url = new URL('/tests/Browser/E4-06F/fixture.html?imports', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('saved counts and original fragments remain visible during review', async ({ page }) => {
  await page.route('**/seller/knowledge/imports/preview', route => route.fulfill({ json: { proposals: ['Первый текст', 'Второй текст'], document_id: '01ARZ3NDEKTSV4RRFFQ69G5FAV', sheets: [], document: { id: '01ARZ3NDEKTSV4RRFFQ69G5FAV', name: 'facts.txt', type: 'txt', pages: null, status: 'previewed', fragments_count: 2, created_at: '2026-11-06' } } }));
  await page.goto(url);
  await expect(page.getByRole('row').filter({ hasText: 'Ранее.pdf' })).toContainText('7');
  await page.getByLabel('Файл', { exact: true }).setInputFiles({ name: 'facts.txt', mimeType: 'text/plain', buffer: Buffer.from('facts') });
  await page.getByRole('button', { name: 'Посмотреть предложения' }).click();
  await expect(page.getByText(/facts\.txt · предложено фактов: 2/)).toBeVisible();
  await page.getByText('Фрагменты документа').click();
  await page.getByRole('button', { name: 'Первый текст' }).click();
  await expect(page.getByRole('button', { name: 'Первый текст' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Изменить', exact: true }).first().click();
  await page.getByLabel('Текст факта').fill('Исправленный текст');
  await page.getByRole('button', { name: 'Готово' }).click();
  await expect(page.getByRole('listitem').filter({ hasText: 'Первый текст' })).toBeVisible();
  await page.getByRole('button', { name: 'Отклонить', exact: true }).first().click();
  await expect(page.getByRole('listitem').filter({ hasText: 'Первый текст' })).toHaveCount(0);
  await expect(page.getByRole('listitem').filter({ hasText: 'Второй текст' })).toBeVisible();
  await mkdir('.local/screenshots/SP-E4-06F', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/SP-E4-06F/imports.png', fullPage: true });
  await page.getByRole('button', { name: 'К документам' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'facts.txt' })).toContainText('2');
});
