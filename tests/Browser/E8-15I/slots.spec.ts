import { test, expect } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';
let server: ViteDevServer;
let url: string;
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E8-15I/vite.config.ts', server: { host: '127.0.0.1', port: 0, strictPort: false } }); await server.listen(); url = new URL('/tests/Browser/E8-15I/fixture.html', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('календарная оценка и выбор периода', async ({ page }) => {
  await page.goto(url);
  await page.getByRole('button', { name: 'Слоты', exact: true }).click();
  await expect(page.getByText('До конца текущего календарного месяца: запуски: 5 × вопросы: 5 × модели: 1 = 25 слотов.')).toBeVisible();
  await expect(page.getByText('За выбранный период: запуски: 5 × вопросы: 5 × модели: 1 = 25 слотов.')).toBeVisible();
  await expect(page.getByText('Ручные запуски не включены.', { exact: false })).toBeVisible();
  await expect(page.getByLabel('Начало периода оценки')).toHaveValue('2026-11-01');
  await expect(page.getByLabel('Конец периода оценки')).toHaveValue('2026-11-30');
  await mkdir('.local/screenshots/SP-E8-15I', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/SP-E8-15I/slots.png', fullPage: true });
  await page.getByLabel('Начало периода оценки').fill('2026-11-09');
  await page.route('**/vision/settings?*', route => route.abort());
  const request = page.waitForRequest(request => request.url().includes('estimate_from=2026-11-09'));
  await page.getByRole('button', { name: 'Рассчитать период' }).click();
  expect((await request).url()).toContain('estimate_to=2026-11-30');
});
