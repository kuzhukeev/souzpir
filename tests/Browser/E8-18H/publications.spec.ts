import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { createServer, type ViteDevServer } from 'vite';
let server: ViteDevServer;
let fixture: string;
test.setTimeout(60000);
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server=await createServer({configFile:'tests/Browser/E8-18F/vite.config.ts'}); await server.listen(); fixture=new URL('/tests/Browser/E8-18H/fixture.html',server.resolvedUrls!.local[0]).href; });
test.afterAll(async()=>{await server?.close();});
test('выбор предложений привязан к отчёту и передаётся явно',async({page})=>{
  await page.route('**/vision/publications?**',route=>{const id=new URL(route.request().url()).searchParams.get('review_report'); return route.fulfill({headers:{'X-Inertia':'true'},json:{component:'Fixture',props:{review:{report_id:id,candidates:[{key:'action:0',title:'Изучить ответы на этот вопрос',why:'Причины не установлены.',question_id:'q1'}]}},url:route.request().url(),version:null,clearHistory:false,encryptHistory:false}});});
  let body: Record<string,unknown> | null=null;
  await page.route('**/vision/publications',route=>{if(route.request().method()==='POST'){body=route.request().postDataJSON();return route.abort();}return route.continue();});
  await page.goto(fixture);
  const choice=page.getByRole('checkbox',{name:/Изучить ответы/});
  await expect(choice).toBeVisible();
  await choice.check();
  await mkdir('.local/screenshots/SP-E8-18H',{recursive:true});
  await page.screenshot({path:'.local/screenshots/SP-E8-18H/publications.png',fullPage:true});
  await page.locator('select').first().selectOption('r2');
  await expect(choice).not.toBeChecked();
  await expect(page.getByRole('button',{name:'Создать ссылку'})).toBeEnabled();
  body=null;
  await page.getByRole('button',{name:'Создать ссылку'}).click();
  await expect.poll(()=>body).not.toBeNull();
  expect(body!.confirmed_actions).toEqual([]);
});
