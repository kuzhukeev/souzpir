import { expect, test } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';
let server: ViteDevServer; let url: string;
test.setTimeout(60000);
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E4-06K/vite.config.ts' }); await server.listen(); url = new URL('/tests/Browser/E4-06K/fixture.html?imports', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('меню действий доступно с клавиатуры и закрывается по Escape', async ({ page }) => {
 await page.goto(url);
 const toggle = page.getByLabel('Действия: Ранее.pdf');
 await toggle.focus(); await page.keyboard.press('Enter');
 await expect(page.getByRole('button', { name: 'Посмотреть', exact: true })).toBeVisible();
 await expect(page.getByRole('link', { name: 'Скачать исходник' })).toBeVisible();
 await mkdir('.local/screenshots/SP-E4-06K', { recursive: true });
 await page.screenshot({ path: '.local/screenshots/SP-E4-06K/menu.png', fullPage: true });
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button', { name: 'Посмотреть', exact: true })).toBeHidden();
 await expect(toggle).toBeFocused();
 await expect(page.getByRole('row').filter({ hasText: 'Старый.txt' })).toContainText('Исходник недоступен');
});
