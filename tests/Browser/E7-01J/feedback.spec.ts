import {expect, test} from '@playwright/test';
import {createServer, type ViteDevServer} from 'vite';
import {mkdir} from 'node:fs/promises';
let server: ViteDevServer; let url: string;
test.use({viewport: {width: 1440, height: 900}, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? {executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH} : {}});
test.beforeAll(async () => { server = await createServer({configFile: 'tests/Browser/E7-01J/vite.config.ts', cacheDir: '.local/runtime/vite-e701j', server: {host: '127.0.0.1', port: 0, strictPort: false}}); await server.listen(); url = new URL('/tests/Browser/E7-01J/fixture.html', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('форма несогласия показывает поля и отправляет мнение', async ({page}) => {
  await page.goto(url);
  await page.getByRole('button', {name: 'Не согласен с оценкой'}).click();
  await page.getByLabel('Ваша оценка').selectOption('3');
  await page.getByLabel('Комментарий').fill('Нужно уточнить факт.');
  await mkdir('.local/screenshots/SP-E7-01J', {recursive: true});
  await page.screenshot({path: '.local/screenshots/SP-E7-01J/feedback.png', fullPage: true});
  let payload: Record<string, unknown> | null = null;
  await page.route('**/seller/quality/evaluations/e/disagree', async route => {payload = route.request().postDataJSON(); await route.abort();});
  await page.getByRole('button', {name: 'Сохранить мнение'}).click();
  await expect.poll(() => payload?.rating).toBe(3);
  await expect(page.getByRole('status')).toContainText('Не удалось связаться с сервером.');
});
