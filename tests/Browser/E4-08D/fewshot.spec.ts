import { expect, test } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { mkdir } from 'node:fs/promises';

let server: ViteDevServer;
let url: string;
test.setTimeout(60000);
test.use({ viewport: { width: 1440, height: 900 }, launchOptions: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {} });
test.beforeAll(async () => { server = await createServer({ configFile: 'tests/Browser/E4-08D/vite.config.ts', server: { host: '127.0.0.1', port: 0, strictPort: false } }); await server.listen(); url = new URL('/tests/Browser/E4-08D/fixture.html', server.resolvedUrls!.local[0]).href; });
test.afterAll(async () => { await server?.close(); });
test('теги, лимит персонажа и выбор из диалога', async ({ page }) => {
  await page.route('**/seller/knowledge/fewshot/dialogs?*', async route => { await new Promise(resolve => setTimeout(resolve, 500)); await route.fulfill({ json: { dialogs: [{ id: '01J00000000000000000000005', name: 'Мария' }] } }); });
  await page.route('**/seller/knowledge/fewshot/dialogs/01J00000000000000000000005', route => route.fulfill({ json: { messages: [{ id: '01J00000000000000000000006', text: 'Уточню условия вашей доставки.' }] } }));
  await page.goto(url);
  const tags = page.getByRole('group', { name: 'Фильтр по тегу' });
  await tags.getByRole('button', { name: 'price' }).click();
  await expect(page.getByText('В какой город отправить заказ?')).toHaveCount(0);
  await expect(page.getByText('Цена указана на сайте.')).toBeVisible();
  await tags.getByRole('button', { name: 'Все' }).click();
  await page.getByLabel('Ответ', { exact: true }).fill('Один два три четыре');
  await expect(page.getByText('Текст длиннее лимита персонажа: слов: 4, лимит: 3.')).toBeVisible();
  await page.getByLabel('Уверенность', { exact: true }).fill('0.72');
  await expect(page.getByText('0.72', { exact: true })).toBeVisible();
  await mkdir('.local/screenshots/SP-E4-08D', { recursive: true });
  await page.screenshot({ path: '.local/screenshots/SP-E4-08D/main.png', fullPage: true });
  await page.locator('button[aria-haspopup="dialog"]').filter({ hasText: 'Добавить из диалога' }).click();
  const modal = page.getByRole('dialog', { name: 'Добавить из диалога' });
  await expect(modal).toBeVisible();
  await modal.getByRole('button', { name: 'Найти' }).click();
  await expect(modal.getByRole('status').filter({ hasText: 'Загружаем данные' })).toBeVisible();
  await modal.getByRole('radio', { name: /Мария/ }).check();
  await modal.getByRole('radio', { name: 'Уточню условия вашей доставки.' }).check();
  await expect(modal.getByText('Текст длиннее лимита персонажа: слов: 4, лимит: 3.')).toBeVisible();
  await page.screenshot({ path: '.local/screenshots/SP-E4-08D/dialog.png' });
  await page.keyboard.press('Escape');
  await expect(modal).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('button[aria-haspopup="dialog"]').filter({ hasText: 'Добавить из диалога' }).click();
  await expect(modal).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
test('ошибка загрузки диалогов остаётся внутри формы', async ({ page }) => {
  await page.route('**/seller/knowledge/fewshot/dialogs?*', route => route.fulfill({ status: 500, body: 'error' }));
  await page.goto(url);
  await page.locator('button[aria-haspopup="dialog"]').filter({ hasText: 'Добавить из диалога' }).click();
  const modal = page.getByRole('dialog', { name: 'Добавить из диалога' });
  await modal.getByRole('button', { name: 'Найти' }).click();
  await expect(modal.getByRole('alert')).toContainText('Не удалось загрузить диалоги.');
});
