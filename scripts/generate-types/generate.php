<?php

use App\Providers\Features\FeatureRegistry;
use Illuminate\Contracts\Console\Kernel;
use Spatie\TypeScriptTransformer\TypeScriptTransformer;
use Spatie\TypeScriptTransformer\TypeScriptTransformerConfigFactory;
use Spatie\TypeScriptTransformer\Writers\FlatModuleWriter;
use Tighten\Ziggy\Output\Types;
use Tighten\Ziggy\Ziggy;

$root = dirname(__DIR__, 2);
require $root.'/vendor/autoload.php';
require __DIR__.'/OptInDataTransformer.php';
require __DIR__.'/OptInEnumTransformer.php';
$app = require $root.'/bootstrap/app.php';
$app->make(Kernel::class)->bootstrap();

$temp = $root.'/.local/runtime/types-'.bin2hex(random_bytes(8));
if (! mkdir($temp, 0700, true) && ! is_dir($temp)) {
    throw new RuntimeException('Unable to create isolated type generation directory.');
}

$exitCode = 0;
try {
    $factory = TypeScriptTransformerConfigFactory::create()
        ->outputDirectory($temp)
        ->transformDirectories($root.'/app')
        ->transformer(new OptInDataTransformer, new OptInEnumTransformer)
        ->writer(new FlatModuleWriter('data.ts'))
        ->withoutManifest();
    TypeScriptTransformer::create($factory)->execute();
    $data = file_get_contents($temp.'/data.ts');
    if ($data === false || ! str_contains($data, 'SharedPropsV1')) {
        throw new RuntimeException('SharedPropsV1 was not generated.');
    }
    // PHP mixed may contain untrusted server data; consumers must narrow it first.
    $data = preg_replace('/\bany\b/', 'unknown', $data);

    $keys = array_keys($app->make(FeatureRegistry::class)->translations());
    $abilities = array_keys(config('permissions.abilities', []));
    sort($keys, SORT_STRING);
    sort($abilities, SORT_STRING);
    $union = static fn (array $values): string => $values === [] ? 'never' : implode(' | ', array_map(
        static fn (string $value): string => json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR),
        $values,
    ));
    $translations = "// Generated by scripts/generate-types/generate.php; do not edit.\nexport type TranslationKey = ".$union($keys).";\n";
    $permissions = "// Generated by scripts/generate-types/generate.php; do not edit.\nexport type PermissionAbility = ".$union($abilities).";\n";

    $routes = (string) new Types((new Ziggy)->filter(['generated::*'], false));
    $routes .= "\ndeclare module 'ziggy-js' { interface TypeConfig { strictRouteNames: true; } }\n";
    $files = ['data.ts' => $data, 'translations.ts' => $translations, 'permissions.ts' => $permissions, 'routes.d.ts' => $routes];
    $outputArgs = array_values(array_filter($argv, static fn (string $argument): bool => str_starts_with($argument, '--output-dir=')));
    if (count($outputArgs) > 1) {
        throw new InvalidArgumentException('Only one output directory may be provided.');
    }
    $target = $outputArgs ? substr($outputArgs[0], strlen('--output-dir=')) : $root.'/resources/js/types/generated';
    if (! is_dir($target) && ! mkdir($target, 0775, true) && ! is_dir($target)) {
        throw new RuntimeException('Unable to create generated type directory.');
    }
    $check = in_array('--check', $argv, true);
    foreach ($files as $name => $contents) {
        $destination = $target.'/'.$name;
        if ($check) {
            if (! is_file($destination) || file_get_contents($destination) !== $contents) {
                throw new RuntimeException("Generated frontend contract is stale: {$name}");
            }
        } elseif (file_put_contents($destination, $contents) === false) {
            throw new RuntimeException("Unable to write generated type: {$name}");
        }
    }
    echo $check ? "Generated frontend contracts match.\n" : "Frontend contracts generated.\n";
} catch (Throwable $error) {
    fwrite(STDERR, $error->getMessage()."\n");
    $exitCode = 1;
} finally {
    foreach (glob($temp.'/*') ?: [] as $file) {
        if (is_file($file)) {
            unlink($file);
        }
    }
    rmdir($temp);
}
exit($exitCode);
