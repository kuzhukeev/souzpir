<?php

namespace App\Seller\Engine;

use SensitiveParameter;

/**
 * Donor reference calculation only. Its indicative prices are not approved
 * configuration and must not be exposed to customers or sent to a model.
 */
final class PrototypeDeliveryEstimate
{
    public function calculate(#[SensitiveParameter] string $city): array
    {
        $normalized = mb_strtolower(trim($city));
        $table = [
            ['rx' => '/москв|подмоск|московск/u', 'cost' => 'бесплатно до терминала ТК / самовывоз', 'days' => '0–1'],
            ['rx' => '/воронеж|тул|рязан|калуг|твер|ярослав|владимир|смолен|орл|курск|белгород|липецк|тамбов|брянск|иванов|костром/u', 'cost' => '1 500–3 000 руб.', 'days' => '2–4'],
            ['rx' => '/петербург|спб|питер|вологд|новгород|псков|петрозаводск|мурманск|архангельск/u', 'cost' => '2 000–4 000 руб.', 'days' => '2–5'],
            ['rx' => '/нижн|казан|самар|саратов|пенз|ульянов|чебоксар|йошкар|киров|ижевск|уфа|оренбург|пермь/u', 'cost' => '2 500–6 000 руб.', 'days' => '3–6'],
            ['rx' => '/краснодар|ростов|ставропол|сочи|волгоград|астрахан|махачкал|грозн|нальчик|владикавказ|севастопол|симферопол|крым/u', 'cost' => '3 000–7 000 руб.', 'days' => '4–7'],
            ['rx' => '/екатеринбург|челябинск|тюмен|курган|сургут|нижневартовск|ханты|магнитогорск/u', 'cost' => '4 000–8 000 руб.', 'days' => '5–8'],
            ['rx' => '/новосибирск|омск|томск|кемеров|новокузнецк|барнаул|красноярск|абакан|иркутск|улан|чита/u', 'cost' => '5 000–12 000 руб.', 'days' => '7–12'],
            ['rx' => '/якут/u', 'cost' => '8 000–15 000 руб.', 'days' => '7–10'],
            ['rx' => '/хабаровск|владивосток|благовещенск|магадан|камчат|сахалин|южно/u', 'cost' => '10 000–25 000 руб.', 'days' => '10–21'],
        ];
        foreach ($table as $row) {
            if ($normalized && preg_match($row['rx'], $normalized)) {
                return ['result' => ['city' => $city, 'cost_range' => $row['cost'], 'days' => $row['days'], 'carrier' => 'КИТ', 'note' => 'ориентир на заказ ~100 тыс. руб. (10–15 коробок); точный расчёт делает менеджер на сайте ТК']];
            }
        }

        return ['result' => ['city' => $city, 'cost_range' => 'нужен расчёт на сайте ТК', 'days' => '3–14', 'carrier' => 'КИТ', 'note' => 'город не в таблице ориентиров — пообещать расчёт и записать обещание']];
    }
}
