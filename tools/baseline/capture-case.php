function prepareCase(string $id, array $original, array $sources): array
{
    $normalizer = new ContactNormalizer;
    // Preseed every authored contact before any result: later source contacts cannot
    // collide with an address first generated by the model during capture.
    $normalizer->assertOriginal([$sources, $original]);
    $normalizer->normalize(FixtureClient::canonical($sources));
    $scenario = FixtureClient::canonical($normalizer->normalize(FixtureClient::canonical($original)));
    $kind = str_starts_with($id, 'persona.') ? 'persona' : 'manual';
    $layer = $kind === 'persona' ? 'donor_orchestrator_persona'
        : (isset($scenario['scheduler_hours']) ? 'donor_orchestrator_setup_and_scheduler' : 'donor_orchestrator_scripted');
    return [$normalizer, ['id'=>$id, 'kind'=>$kind, 'execution_layer'=>$layer, 'scenario'=>$scenario,
        'scenario_sha256'=>hash('sha256', FixtureClient::json($scenario))]];
}
