function resultProjection(array $result): array
{
    $meta = $result['meta'];
    unset($meta['latency_ms'], $meta['message_id']);
    return ['reply'=>$result['reply'], 'meta'=>$meta, 'state'=>$result['lead']->state,
        'stage'=>$result['lead']->stage, 'outcome'=>$result['lead']->outcome];
}
